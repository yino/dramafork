export type DictKey = keyof typeof DICT.en;

export function t(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let str: string = DICT[locale][key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}

export function fieldLabel(locale: Locale, kind: CreationKind, fieldKey: string): string {
  const cap = kind === 'film' ? 'Film' : kind === 'text' ? 'Text' : 'Character';
  if (fieldKey === 'summary') return t(locale, `summary${cap}` as DictKey);
  if (fieldKey === 'tone') return t(locale, `tone${cap}` as DictKey);
  if (fieldKey === 'coreExperience') return t(locale, `coreExperience${cap}` as DictKey);
  return t(locale, fieldKey as DictKey);
}
